/// 생성기 공통 — 이름 바꾸기 · 문자열 리터럴 · 타입 대응
module Emit

open Model

let header = "// <auto-generated/> dsl/Spec.fs 에서 생성됨 — 고치려면 명세를 고친다"
let camel (s: string) = string (System.Char.ToLowerInvariant s[0]) + s[1..]
let pascal (s: string) = string (System.Char.ToUpperInvariant s[0]) + s[1..]

/// C# · JS 공통 문자열 리터럴(큰따옴표)
let lit (s: string) =
    "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n") + "\""

let csType = function Str -> "string" | Int -> "int" | Bool -> "bool" | Strs -> "IReadOnlyList<string>"
let tsType = function Str -> "string" | Int -> "number" | Bool -> "boolean" | Strs -> "string[]"

/// JsonElement r 에서 읽기(C#)
let csRead (n, t) =
    match t with
    | Str -> $"r.GetProperty({lit n}).GetString() ?? \"\""
    | Int -> $"r.GetProperty({lit n}).GetInt32()"
    | Bool -> $"r.GetProperty({lit n}).GetBoolean()"
    | Strs -> $"[.. r.GetProperty({lit n}).EnumerateArray().Select(e => e.GetString() ?? \"\")]"

/// Utf8JsonWriter w 로 쓰기(C#)
let csWrite (n, t) =
    match t with
    | Str -> $"w.WriteString({lit n}, {n});"
    | Int -> $"w.WriteNumber({lit n}, {n});"
    | Bool -> $"w.WriteBoolean({lit n}, {n});"
    | Strs -> $"w.WriteStartArray({lit n}); foreach (var x in {n}) w.WriteStringValue(x); w.WriteEndArray();"

let csParams (fields: (string * Field) list) = fields |> List.map (fun (n, t) -> $"{csType t} {n}") |> String.concat ", "
let lines (xs: string list) = String.concat "\n" xs + "\n"

// ── UI 부품 → C# 식 ── Avalonia 와 Android 가 같은 모양의 도우미(Row · Dot · Label · Glyph · Pill)를 갖는다

let num (v: float) = sprintf "%g" v
let field (prop: string) = "_" + camel prop

let rec valueExpr =
    function
    | Text s | Color s -> lit s
    | Flag b -> if b then "true" else "false"
    | Token t -> $"Tokens.{t}"
    | Prop p -> field p
    | If(p, a, b) -> $"({field p} ? {valueExpr a} : {valueExpr b})"

/// ui 는 도우미를 부르는 앞말("Ui" 또는 "ui")
let rec nodeExpr (ui: string) =
    function
    | Row(sp, xs) -> $"""{ui}.Row({num sp}{xs |> List.map (fun x -> ", " + nodeExpr ui x) |> String.concat ""})"""
    | Dot(size, fill) -> $"{ui}.Dot({num size}, {valueExpr fill})"
    | Label(t, size, bold, color) -> $"{ui}.Label({valueExpr t}, {num size}, {valueExpr bold}, {valueExpr color})"
    | Glyph(g, size, color, ev) -> $"{ui}.Glyph({valueExpr g}, {num size}, {valueExpr color}, () => {ev}?.Invoke(this, EventArgs.Empty))"
    | Pill((l, t, r, b), radius, fill, child) -> $"{ui}.Pill({num l}, {num t}, {num r}, {num b}, {num radius}, {valueExpr fill}, {nodeExpr ui child})"
    | Show(p, n) -> $"({field p} ? {nodeExpr ui n} : null)"

let csPropType = function PText | PColor -> "string" | PFlag -> "bool"
let csPropDefault = function PText -> "\"\"" | PColor -> "\"#000000\"" | PFlag -> "false"

/// 부품 클래스 몸통 — 이벤트 · 속성(바꾸면 다시 그림)
let componentMembers (c: Component) =
    [ for e in c.Events do $"    public event EventHandler? {e};"
      for n, t in c.Props do
          $"    {csPropType t} {field n} = {csPropDefault t};"
          $"    public {csPropType t} {n} {{ get => {field n}; set {{ {field n} = value; Render(); }} }}" ]
