/// UI 부품 → Android 뷰(C#)
module GenAndroid

open Model
open Emit
open Spec

let generate () =
    lines [
        header
        "#nullable enable"
        "using Android.Content;"
        "using Android.Graphics;"
        "using Android.Graphics.Drawables;"
        "using Android.Util;"
        "using Android.Views;"
        "using Android.Widget;"
        "namespace Dsl;"
        ""
        "sealed class Ui(Context context)"
        "{"
        "    readonly float dp = context.Resources!.DisplayMetrics!.Density;"
        "    int Px(double v) => (int)Math.Round(v * dp);"
        "    static Color C(string c) => Color.ParseColor(c);"
        "    const int Wrap = ViewGroup.LayoutParams.WrapContent;"
        "    public View Row(double spacing, params View?[] kids)"
        "    {"
        "        var row = new LinearLayout(context) { Orientation = Orientation.Horizontal };"
        "        row.SetGravity(GravityFlags.CenterVertical);"
        "        var first = true;"
        "        foreach (var k in kids)"
        "        {"
        "            if (k is null) continue;"
        "            var lp = new LinearLayout.LayoutParams(k.LayoutParameters?.Width ?? Wrap, k.LayoutParameters?.Height ?? Wrap) { Gravity = GravityFlags.CenterVertical };"
        "            if (!first) lp.LeftMargin = Px(spacing);"
        "            first = false;"
        "            row.AddView(k, lp);"
        "        }"
        "        return row;"
        "    }"
        "    public View Dot(double size, string fill)"
        "    {"
        "        var g = new GradientDrawable();"
        "        g.SetShape(ShapeType.Oval);"
        "        g.SetColor(C(fill));"
        "        return new View(context) { Background = g, LayoutParameters = new ViewGroup.LayoutParams(Px(size), Px(size)) };"
        "    }"
        "    public TextView Label(string text, double size, bool bold, string color)"
        "    {"
        "        var t = new TextView(context) { Text = text };"
        "        t.SetTextSize(ComplexUnitType.Dip, (float)size);"
        "        t.SetTextColor(C(color));"
        "        t.SetTypeface(null, bold ? TypefaceStyle.Bold : TypefaceStyle.Normal);"
        "        t.SetIncludeFontPadding(false);"
        "        return t;"
        "    }"
        "    public View Glyph(string glyph, double size, string color, Action onTap)"
        "    {"
        "        var t = Label(glyph, size, false, color);"
        "        t.Click += (_, _) => onTap();"
        "        return t;"
        "    }"
        "    public View Pill(double l, double t, double r, double b, double radius, string fill, View? child)"
        "    {"
        "        var g = new GradientDrawable();"
        "        g.SetCornerRadius(Px(radius));"
        "        g.SetColor(C(fill));"
        "        var box = new FrameLayout(context) { Background = g };"
        "        box.SetPadding(Px(l), Px(t), Px(r), Px(b));"
        "        if (child is not null)"
        "            box.AddView(child, new FrameLayout.LayoutParams(child.LayoutParameters?.Width ?? Wrap, child.LayoutParameters?.Height ?? Wrap) { Gravity = GravityFlags.Center });"
        "        return box;"
        "    }"
        "}"
        for c in components do
            ""
            $"/// {c.Doc}"
            $"public sealed class {c.Name} : FrameLayout"
            "{"
            "    readonly Ui ui;"
            yield! componentMembers c
            ""
            $"    public {c.Name}(Context context) : base(context)"
            "    {"
            "        ui = new Ui(context);"
            match c.OnTap with
            | Some e -> $"        Click += (_, _) => {e}?.Invoke(this, EventArgs.Empty);"
            | None -> ()
            "        Render();"
            "    }"
            ""
            "    void Render()"
            "    {"
            "        RemoveAllViews();"
            let root = nodeExpr "ui" c.Root
            $"        AddView({root}, new LayoutParams(ViewGroup.LayoutParams.WrapContent, ViewGroup.LayoutParams.WrapContent) {{ Gravity = GravityFlags.Center }});"
            "    }"
            "}" ]
