/// 모듈 페이지에 넣을 window.app 스크립트
let moduleScript key =
    let granted = grants |> List.tryFind (fst >> (=) key) |> Option.map snd |> Option.defaultValue []
    match capabilities |> List.filter (fun c -> List.contains c.Name granted) with
    | [] -> ""
    | caps ->
        String.concat "\n" [
            "(() => {"
            "  const post = (m) => { const s = JSON.stringify(m); if (window.chrome && window.chrome.webview) window.chrome.webview.postMessage(s); else if (window.appBridge) window.appBridge.postMessage(s); };"
            "  let next = 0; const waiting = new Map();"
            "  const call = (name, args) => new Promise((resolve, reject) => { const id = ++next; waiting.set(id, { resolve, reject }); post({ id, name, ...args }); });"
            "  window.app = {"
            for c in caps do
                let args = c.Args |> List.map fst |> String.concat ", "
                let obj = if c.Args.IsEmpty then "{}" else "{ " + args + " }"
                $"    {camel c.Name}: ({args}) => call('{c.Name}', {obj}),"
            "    __reply: (id, ok, value) => { const w = waiting.get(id); waiting.delete(id); if (w) ok ? w.resolve(value) : w.reject(new Error(value)); },"
            "  };"
            "})();" ]

let generate () =
    let csValue = function Str -> "Json.Str(v)" | Int -> "v.ToString()" | Bool -> "(v ? \"true\" : \"false\")" | Strs -> "\"[\" + string.Join(\",\", v.Select(Json.Str)) + \"]\""
    lines [
        header
        "#nullable enable"
        "using System.Text;"
        "using System.Text.Json;"
        "namespace Dsl;"
        ""
        "static class Json"
        "{"
        "    public static string Write(Action<Utf8JsonWriter> write)"
        "    {"
        "        using var ms = new MemoryStream();"
        "        using (var w = new Utf8JsonWriter(ms)) { w.WriteStartObject(); write(w); w.WriteEndObject(); }"
        "        return Encoding.UTF8.GetString(ms.ToArray());"
        "    }"
        "    /// JS 문자열 리터럴"
        "    public static string Str(string s)"
        "    {"
        "        using var ms = new MemoryStream();"
        "        using (var w = new Utf8JsonWriter(ms)) w.WriteStringValue(s);"
        "        return Encoding.UTF8.GetString(ms.ToArray());"
        "    }"
        "}"
        ""
        "/// 런처 → 앱 — 앱마다 구현한다"
        "public interface ILauncherHandler"
        "{"
        for m in toApp do
            $"    /// {m.Doc}"
            $"    void {m.Name}({csParams m.Fields});"
        "}"
        ""
        "public static class FromLauncher"
        "{"
        "    /// 런처가 보낸 문자열을 읽어 handler 를 부른다. 못 읽으면 그 까닭을 돌려준다"
        "    public static string? Dispatch(string json, ILauncherHandler handler)"
        "    {"
        "        try"
        "        {"
        "            using var doc = JsonDocument.Parse(json);"
        "            var r = doc.RootElement;"
        "            switch (r.GetProperty(\"type\").GetString())"
        "            {"
        for m in toApp do
            $"""                case {lit m.Name}: handler.{m.Name}({m.Fields |> List.map csRead |> String.concat ", "}); return null;"""
        "                case var t: return $\"모르는 메시지 {t}\";"
        "            }"
        "        }"
        "        catch (Exception e) { return e.Message; }"
        "    }"
        "}"
        ""
        "/// 앱 → 런처 — 결과는 런처 웹뷰에서 실행할 스크립트"
        "public static class ToLauncher"
        "{"
        for m in toWeb do
            let body = m.Fields |> List.map csWrite |> String.concat " "
            $"    /// {m.Doc}"
            $"    public static string {m.Name}({csParams m.Fields}) => Script(Json.Write(w => {{ w.WriteString(\"type\", {lit m.Name}); {body} }}));"
        "    static string Script(string json) => $\"window.bridge && window.bridge.receive({Json.Str(json)})\";"
        "}"
        ""
        "/// 앱 → 모듈 페이지 이벤트 — 결과는 모듈 웹뷰에서 실행할 스크립트(window.postMessage)"
        "public static class ModuleEvents"
        "{"
        for m in moduleEvents do
            let body = m.Fields |> List.map csWrite |> String.concat " "
            $"    /// {m.Doc}"
            $"    public static string {pascal m.Name}({csParams m.Fields}) => \"window.postMessage(\" + Json.Write(w => {{ w.WriteString(\"type\", {lit m.Name}); {body} }}) + \", '*')\";"
        "}"
        ""
        "public sealed record Module(string Key, string Name, string Description, string Accent, string Path);"
        ""
        "public static class Modules"
        "{"
        $"    public const string DefaultServer = {lit defaultServer};"
        "    public static readonly IReadOnlyList<Module> All ="
        "    ["
        for m in modules do
            $"        new({lit m.Key}, {lit m.Name}, {lit m.Description}, {lit m.Accent}, {lit m.Path}),"
        "    ];"
        "    public static Module? Find(string key) => All.FirstOrDefault(m => m.Key == key);"
        "}"
        ""
        "/// 모듈 페이지가 부르는 앱 기능 — 앱마다 구현한다. 취소 · 실패면 null"
        "public interface ICapabilities"
        "{"
        for c in capabilities do
            let ret = match c.Returns with Some t -> $"Task<{csType t}?>" | None -> "Task"
            $"    /// {c.Doc}"
            $"""    {ret} {c.Name}({csParams (("moduleKey", Str) :: c.Args)});"""
        "}"
        ""
        "public static class Capabilities"
        "{"
        "    /// 모듈 페이지에 문서 시작 때 넣을 스크립트 — 허락한 기능만 window.app 에. 없으면 \"\""
        "    public static string Script(string moduleKey) => moduleKey switch"
        "    {"
        for key, _ in grants do $"        {lit key} => {lit (moduleScript key)},"
        "        _ => \"\","
        "    };"
        ""
        "    public static bool Allowed(string moduleKey, string name) => (moduleKey, name) switch"
        "    {"
        for key, names in grants do
            for n in names do $"        ({lit key}, {lit n}) => true,"
        "        _ => false,"
        "    };"
        ""
        "    /// 모듈 페이지 요청({ id, name, ...인자 })을 처리하고, 페이지에서 실행할 답 스크립트를 돌려준다"
        "    public static async Task<string> Handle(string moduleKey, string json, ICapabilities impl)"
        "    {"
        "        int id = 0;"
        "        try"
        "        {"
        "            using var doc = JsonDocument.Parse(json);"
        "            var r = doc.RootElement;"
        "            id = r.GetProperty(\"id\").GetInt32();"
        "            var name = r.GetProperty(\"name\").GetString() ?? \"\";"
        "            if (!Allowed(moduleKey, name)) return Deny(id, $\"{moduleKey} 에 허락되지 않은 기능 {name}\");"
        "            switch (name)"
        "            {"
        for c in capabilities do
            let args = ("moduleKey" :: (c.Args |> List.map csRead)) |> String.concat ", "
            match c.Returns with
            | Some t -> $"                case {lit c.Name}: {{ var v = await impl.{c.Name}({args}); return Reply(id, v is null ? \"null\" : {csValue t}); }}"
            | None -> $"                case {lit c.Name}: await impl.{c.Name}({args}); return Reply(id, \"null\");"
        "                default: return Deny(id, $\"모르는 기능 {name}\");"
        "            }"
        "        }"
        "        catch (Exception e) { return Deny(id, e.Message); }"
        "    }"
        ""
        "    static string Reply(int id, string value) => $\"window.app && window.app.__reply({id}, true, {value})\";"
        "    /// 거절 — 페이지의 Promise 가 오류로 끝난다"
        "    public static string Deny(int id, string why) => $\"window.app && window.app.__reply({id}, false, {Json.Str(why)})\";"
        "}"
        ""
        "public static class Scanners"
        "{"
        "    /// (VID, PID) — COM 포트 에뮬레이션(CDC-ACM) 모드"
        "    public static readonly IReadOnlyList<(int Vid, int Pid, string Name)> Devices ="
        "    ["
        for vid, pid, name in scanners do $"        (0x{vid:X4}, 0x{pid:X4}, {lit name}),"
        "    ];"
        $"    public const int BaudRate = {scannerBaudRate};"
        "}"
        ""
        "public static class Tokens"
        "{"
        for n, c in colors do $"    public const string {n} = {lit c};"
        for n, v in sizes do $"    public const double {n} = {v};"
        "}" ]
